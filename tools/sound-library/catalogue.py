#!/usr/bin/env python3
"""THE SOUND LIBRARY · catalogue · 14 Nov 2026.

Ian: "all of the sound effects and score, should they be saved somewhere so they
can be reused?" Every book kept its own sound folder; nothing was shared. This
walks every book's sound.json and writes SOUNDS.json: one entry per reusable
sound (beds, one-shots, fills, score), with its kind, the books that use it, its
file, length and loudness, and the lines of that book's SOURCES.md that name it.
Recorded cues (narration baked with effects) are not reusable and are left out.

Next: the files move to one shared home (the Media Door's R2, under sounds/),
named by key, and sound sheets refer to library keys.
usage: catalogue.py <Amenti-Readings root>
"""
import json, os, re, subprocess, sys, glob
ROOT = sys.argv[1] if len(sys.argv) > 1 else '.'
READ = 'https://ianingram.github.io/Amenti-Readings/'
RAW = 'https://raw.githubusercontent.com/ianingram/Amenti-Readings/main/'

def local(url):
    for pre in (READ, RAW):
        if url.startswith(pre): return os.path.join(ROOT, url[len(pre):])
    return None

def probe(p):
    try:
        d = float(subprocess.run(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', p], capture_output=True, text=True).stdout.strip())
        r = subprocess.run(['ffmpeg', '-hide_banner', '-i', p, '-af', 'ebur128', '-f', 'null', '-'], capture_output=True, text=True).stderr
        m = re.findall(r'^\s+I:\s+(-?[\d.]+) LUFS', r, re.M)
        return round(d, 2), (float(m[-1]) if m else None)
    except Exception:
        return None, None

lib = {}
for sj in sorted(glob.glob(os.path.join(ROOT, '*', 'sound.json'))):
    book = sj.split(os.sep)[-2]
    s = json.load(open(sj)); f = s.get('files', {})
    base = f.get('base') or (RAW + book + '/sound/')
    src = ''
    sp = os.path.join(ROOT, book, 'sound', 'SOURCES.md')
    if os.path.exists(sp): src = open(sp, encoding='utf-8', errors='replace').read()
    for kind, plural in (('bed', 'beds'), ('oneshot', 'oneshots'), ('fill', 'under'), ('score', 'score')):
        for key, name in (f.get(plural) or {}).items():
            if not isinstance(name, str): continue
            url = name if re.match(r'https?:', name) else base + name
            p = local(url)
            if not p or not os.path.exists(p): continue
            rel = os.path.relpath(p, ROOT)
            e = lib.get(rel)
            if not e:
                dur, lufs = probe(p)
                fn = os.path.basename(p)
                credit = [ln.strip() for ln in src.splitlines() if fn in ln or re.search(r'\b' + re.escape(key) + r'\b', ln)][:4]
                e = lib[rel] = {'key': key, 'kind': kind, 'file': rel, 'seconds': dur, 'lufs': lufs,
                                'books': [], 'level': None, 'credit': credit}
                if kind == 'score': e['level'] = (f.get('levels') or {}).get(key)
                if kind == 'oneshot': e['level'] = (f.get('sfx_levels') or {}).get(key)
            if book not in e['books']: e['books'].append(book)
out = sorted(lib.values(), key=lambda e: (e['kind'], e['key']))
by = {}
for e in out: by[e['kind']] = by.get(e['kind'], 0) + 1
json.dump({'_': 'GENERATED by tools/sound-library/catalogue.py. The shared sound library of Amenti Studios.',
           'counts': by, 'sounds': out}, open(os.path.join(ROOT, 'SOUNDS.json'), 'w'), indent=1, ensure_ascii=False)
print(len(out), 'sounds', by, '·', round(sum((e['seconds'] or 0) for e in out) / 60, 1), 'minutes')
